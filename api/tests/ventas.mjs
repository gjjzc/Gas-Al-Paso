import { iniciar, req, cliente, repartidor, producto, web, entregar, cerrar, ok, igual, mongoDb, redisClient, direccion, marca } from './tests/soporte/verificaciones.mjs';
try {
  const admin = await iniciar(), c = await cliente(), ajeno = await cliente(), r = await repartidor(admin);
  const p = await producto(admin, { stock: 10 });
  const carro = await req('POST', '/carrito/items', { id_producto: p.id_producto, cantidad: 2 }, c.token);
  igual(new Date(carro.expira_en) - new Date(carro.actualizado_en), 1800000);
  const hash = await redisClient.hGetAll(`carrito:${c.id_cliente}`);
  igual(Object.keys(hash), [String(p.id_producto)]);
  igual(Object.keys(JSON.parse(hash[p.id_producto])).sort(), ['cantidad', 'nombre', 'precio_unitario']);
  ok(await redisClient.ttl(`carrito:${c.id_cliente}`) > 1700);
  const lectura = await req('GET', '/carrito', undefined, c.token);
  igual(lectura.expira_en, carro.expira_en, 'GET no renueva TTL');
  await req('POST', '/pedidos', { direccion_entrega: { ...direccion, id_comuna: 999999 }, metodo_cobro: 'EFECTIVO' }, c.token, 404);
  const pedido = await req('POST', '/pedidos', { direccion_entrega: direccion, metodo_cobro: 'EFECTIVO' }, c.token, 201, 'web-'+marca);
  igual([pedido.subtotal, pedido.descuento, pedido.total, pedido.estado_pago], [30000, 3000, 27000, 'PENDIENTE']);
  const repetido = await req('POST', '/pedidos', { direccion_entrega: direccion, metodo_cobro: 'EFECTIVO' }, c.token, 200, 'web-'+marca);
  igual(repetido.id_venta, pedido.id_venta); ok(repetido.reutilizada);
  igual((await mongoDb.collection('catalogo').findOne({ id_producto: p.id_producto })).stock, 8);
  igual((await req('GET', '/carrito', undefined, c.token)).items.length, 0);
  await req('GET', `/pedidos/${pedido._id}`, undefined, ajeno.token, 404);
  const entregado = await entregar(admin, r, pedido, 'TRANSFERENCIA');
  igual(entregado.estado_pago, 'COBRADA'); igual(entregado.metodo_pago, 'TRANSFERENCIA');
  const otraEntrega = await req('PATCH', `/pedidos/${pedido._id}/estado`, { estado: 'ENTREGADO', metodo_pago: 'TRANSFERENCIA' }, r.token);
  igual(otraEntrega.version, entregado.version);
  await req('PATCH', `/pedidos/${pedido._id}/estado`, { estado: 'ENTREGADO', metodo_pago: 'EFECTIVO' }, r.token, 409);
  await req('PATCH', `/pedidos/${pedido._id}/cancelar`, {}, admin, 409);
  const cancelado = await web(ajeno, p, 1);
  await Promise.all([1, 2].map(() => req('PATCH', `/pedidos/${cancelado._id}/cancelar`, {}, admin)));
  igual((await mongoDb.collection('catalogo').findOne({ id_producto: p.id_producto })).stock, 8, 'Cancelar repone una sola vez');
  await req('DELETE', `/pedidos/${cancelado._id}`, undefined, admin);
  igual(await mongoDb.collection('pedidos').countDocuments({ id_venta: cancelado.id_venta }), 0, 'Borrado físico');
  const audit = await mongoDb.collection('eventos_auditoria').findOne({ tipo: 'PEDIDO_ELIMINADO', 'detalle.id_venta': cancelado.id_venta });
  ok(audit && audit.detalle.items.length && audit.detalle.total === cancelado.total, 'Snapshot auditado antes de borrar');
  const escaso = await producto(admin, { stock: 1 });
  const a = await cliente(), b = await cliente();
  for (const cl of [a, b]) await req('POST', '/carrito/items', { id_producto: escaso.id_producto, cantidad: 1 }, cl.token);
  const carreras = await Promise.all([a, b].map(cl => req('POST', '/pedidos', { direccion_entrega: direccion, metodo_cobro: 'EFECTIVO' }, cl.token, [201, 409])));
  igual(carreras.filter(d => d.id_venta).length, 1, 'Un solo comprador obtiene la última unidad');
  igual((await mongoDb.collection('catalogo').findOne({ id_producto: escaso.id_producto })).stock, 0);
  const rollback = await cliente();
  for (const pr of [p, escaso]) await req('POST', '/carrito/items', { id_producto: pr.id_producto, cantidad: 1 }, rollback.token);
  const stockAntes = (await mongoDb.collection('catalogo').findOne({ id_producto: p.id_producto })).stock;
  const pedidosAntes = await mongoDb.collection('pedidos').countDocuments({ 'cliente.id_cliente': rollback.id_cliente });
  await req('POST', '/pedidos', { direccion_entrega: direccion, metodo_cobro: 'EFECTIVO' }, rollback.token, 409);
  igual(await mongoDb.collection('pedidos').countDocuments({ 'cliente.id_cliente': rollback.id_cliente }), pedidosAntes, 'No queda un pedido parcial');
  igual((await mongoDb.collection('catalogo').findOne({ id_producto: p.id_producto })).stock, stockAntes, 'Rollback de todas las líneas');
  const dia = await req('GET', '/ventas/dia', undefined, r.token);
  igual(dia.resumen.transferencia, 27000); igual(dia.resumen.efectivo, 0);
  const otrasVentas = await req('GET', `/ventas/dia?id_empleado=${r.id_empleado}`, undefined, admin);
  igual(otrasVentas.resumen.total_cobrado, dia.resumen.total_cobrado);
  const pedidos = await req('GET', '/pedidos/asignados', undefined, r.token);
  ok(pedidos.some(x => x.id_venta === pedido.id_venta));
  const stockAudit = await mongoDb.collection('eventos_auditoria').countDocuments({ tipo: 'CAMBIO_STOCK', 'detalle.id_venta': pedido.id_venta });
  igual(stockAudit, 1);
} finally { await cerrar('M3 VENTAS'); }
