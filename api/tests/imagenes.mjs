import { iniciar, req, cliente, producto, web, cerrar, ok, igual, mongoDb, redisClient } from './tests/soporte/verificaciones.mjs';
try {
  const admin = await iniciar(), c = await cliente();
  const p = await producto(admin, { imagen: '/productos/balon-11kg.webp' });
  await req('GET', '/catalogo?limite=100');
  ok(await redisClient.exists('catalogo:publico'));
  ok(await redisClient.ttl('catalogo:publico') > 0 && await redisClient.ttl('catalogo:publico') <= 30);
  await req('PATCH', `/productos/${p.id_producto}`, { precio: 16000 }, admin);
  igual(await redisClient.exists('catalogo:publico'), 0, 'PATCH invalida la lista pública');
  const nuevo = await req('GET', `/catalogo?buscar=${encodeURIComponent(p.nombre)}`);
  igual(nuevo[0].precio, 16000);
  const auditoria = await req('GET', '/auditoria?tipo=CAMBIO_PRECIO&limite=100', undefined, admin);
  ok(auditoria.some(e => e.detalle.id_producto === p.id_producto && e.detalle.antes === 15000 && e.detalle.despues === 16000));
  await req('PATCH', `/productos/${p.id_producto}`, { precio: 16000 }, admin);
  igual(await mongoDb.collection('eventos_auditoria').countDocuments({ tipo: 'CAMBIO_PRECIO', 'detalle.id_producto': p.id_producto }), 3, 'También audita el precio actualizado al mismo valor');
  await req('PUT', `/catalogo/${p.id_producto}`, { imagen: '/productos/CONTROL.PNG' }, admin);
  await req('PUT', `/catalogo/${p.id_producto}`, { imagen: p.imagen }, admin);
  const ped = await web(c, p, 2);
  igual(ped.items[0].imagen, p.imagen); igual(ped.total, 28800);
  await req('PUT', `/catalogo/${p.id_producto}`, { imagen: '/productos/balon-15kg.webp', nombre: 'Nombre posterior' }, admin);
  const antes = await req('GET', `/pedidos/${ped._id}`, undefined, c.token);
  igual(antes.items[0].nombre, p.nombre); igual(antes.items[0].imagen, p.imagen);
  const vacio = await req('PUT', `/catalogo/${p.id_producto}`, { imagen: '' }, admin);
  igual(vacio.imagen, '/llama.svg');
  await req('PUT', `/catalogo/${p.id_producto}`, { imagen: 'https://externo.test/imagen.png' }, admin, 400);
  await req('DELETE', `/catalogo/${p.id_producto}`, undefined, admin);
  igual(await redisClient.exists('catalogo:publico'), 0);
  await req('PATCH', `/pedidos/${ped._id}/cancelar`, {}, c.token);
  igual((await mongoDb.collection('catalogo').findOne({ id_producto: p.id_producto })).stock, p.stock, 'Cancelar devuelve stock aunque esté inactivo');
} finally { await cerrar('M3 IMÁGENES Y CACHÉ'); }
