import { iniciar, req, cliente, repartidor, producto, cerrar, ok, igual, mongoDb, clave, marca } from './tests/soporte/verificaciones.mjs';
try {
  const admin = await iniciar();
  const c = await cliente(), r = await repartidor(admin);
  const me = await req('GET', '/auth/me', undefined, c.token);
  ok(me.activo && me.rol === 'CLIENTE' && Number.isInteger(me.id_cliente), 'Registro público con IDs numéricos');
  ok(!('password_hash' in me) && !('_id' in me) && !('token_version' in me), 'No se exponen campos internos');
  await req('GET', '/usuarios', undefined, c.token, 403);
  await req('GET', '/usuarios', undefined, undefined, 401);
  const comunas = await req('GET', '/comunas'); igual(comunas.length, 8);
  const reps = await req('GET', '/repartidores?comuna=1', undefined, admin);
  ok(reps.some(e => e.id_empleado === r.id_empleado && e.cubre_comuna), 'Cobertura inicial');
  await req('PUT', `/repartidores/${r.id_empleado}/comunas`, { comunas: [2, 3] }, admin);
  await req('PUT', `/repartidores/${r.id_empleado}/comunas`, { comunas: [999999] }, admin, 400);
  const repInfo = await req('GET', '/repartidores?comuna=2', undefined, admin);
  igual(repInfo.find(e => e.id_empleado === r.id_empleado).comunas.map(c => c.id_comuna).sort(), [2, 3]);
  const nombreCorto = await req('PATCH', `/usuarios/${c.id_usuario}`, { nombre: 'A' }, admin);
  igual(nombreCorto.nombre, 'A', 'Conserva el contrato de edición de usuarios');
  const nuevoPassword = clave();
  await req('PATCH', `/usuarios/${c.id_usuario}`, { password: nuevoPassword }, admin);
  await req('GET', '/auth/me', undefined, c.token, 401);
  await req('POST', '/auth/login', { email: c.email, password: nuevoPassword });
  const uAdmin = await req('GET', '/auth/me', undefined, admin);
  await req('PATCH', `/usuarios/${uAdmin.id_usuario}`, { activo: false }, admin, 409);
  await req('PATCH', `/usuarios/${c.id_usuario}`, { rol: 'REPARTIDOR' }, admin, 409);
  const antes = await mongoDb.collection('empleados').countDocuments();
  await req('POST', '/usuarios', { nombre: 'No crear', email: `${marca}@operaciones.test`, password: clave(), rol: 'REPARTIDOR', comunas: [999999] }, admin, 400);
  igual(await mongoDb.collection('empleados').countDocuments(), antes, 'Rollback del alta inválida');
  const p = await producto(admin);
  await req('POST', '/catalogo', { nombre: 'No crear', descripcion: 'Fallido', categoria: 'GAS', peso: 11, precio: 1, stock: -1 }, admin, 400);
  await req('DELETE', `/catalogo/${p.id_producto}`, undefined, admin);
  await req('GET', `/catalogo/${p.id_producto}`, undefined, undefined, 404);
  await req('GET', `/catalogo/${p.id_producto}?incluir_inactivos=true`, undefined, admin);
  await req('POST', '/sincronizacion/reintentar', undefined, admin, 404);
} finally { await cerrar('M3 API'); }
