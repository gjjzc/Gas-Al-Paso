PROMPT 02 - Ampliando el modelo relacional
-- Scripts ordenados para un volumen nuevo; NO repetir sobre una base con datos.
CREATE TABLE Comuna (
    id_comuna NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(80) NOT NULL UNIQUE
);
CREATE TABLE Cliente (
    id_cliente NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    telefono VARCHAR2(20) NOT NULL,
    direccion_principal VARCHAR2(200) NOT NULL,
    id_comuna NUMBER NOT NULL REFERENCES Comuna(id_comuna)
);
CREATE TABLE Usuario (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR2(254) NOT NULL UNIQUE,
    password_hash VARCHAR2(100) NOT NULL,
    rol VARCHAR2(15) NOT NULL CHECK (rol IN ('CLIENTE', 'REPARTIDOR', 'ADMIN')),
    activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0,1)),
    id_empleado NUMBER UNIQUE REFERENCES Empleado(id_empleado),
    id_cliente NUMBER UNIQUE REFERENCES Cliente(id_cliente),
    CONSTRAINT ck_usuario_email CHECK (email = LOWER(TRIM(email))),
    CONSTRAINT ck_usuario_vinculo CHECK (
        (rol = 'CLIENTE' AND id_cliente IS NOT NULL AND id_empleado IS NULL)
        OR (rol IN ('ADMIN','REPARTIDOR') AND id_empleado IS NOT NULL AND id_cliente IS NULL)
    )
);
CREATE TABLE Repartidor_Comuna (
    id_empleado NUMBER NOT NULL REFERENCES Empleado(id_empleado),
    id_comuna NUMBER NOT NULL REFERENCES Comuna(id_comuna),
    PRIMARY KEY (id_empleado, id_comuna)
);
ALTER TABLE Productos ADD (activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0,1)));
ALTER TABLE Venta ADD (
    canal VARCHAR2(10) DEFAULT 'WEB' NOT NULL CHECK (canal IN ('WEB','LLAMADA','TARREO')),
    id_cliente NUMBER REFERENCES Cliente(id_cliente),
    estado_pago VARCHAR2(10) DEFAULT 'PENDIENTE' NOT NULL CHECK (estado_pago IN ('PENDIENTE','COBRADA','ANULADA')),
    metodo_pago VARCHAR2(15) CHECK (metodo_pago IN ('EFECTIVO','TRANSFERENCIA')),
    id_pedido_mongo VARCHAR2(24) UNIQUE,
    estado_registro VARCHAR2(10) DEFAULT 'CONFIRMADA' NOT NULL CHECK (estado_registro IN ('BORRADOR','CONFIRMADA')),
    CONSTRAINT ck_venta_cobro CHECK (estado_pago <> 'COBRADA' OR metodo_pago IS NOT NULL),
    CONSTRAINT ck_venta_cliente CHECK ((canal = 'TARREO' AND id_cliente IS NULL) OR (canal IN ('WEB','LLAMADA') AND id_cliente IS NOT NULL)),
    CONSTRAINT ck_venta_mongo CHECK (id_pedido_mongo IS NULL OR REGEXP_LIKE(id_pedido_mongo, '^[0-9a-f]{24}$'))
);
ALTER TABLE Detalle_venta ADD CONSTRAINT uq_detalle_producto UNIQUE (id_venta,id_producto);
CREATE INDEX ix_venta_fecha_empleado ON Venta(fecha_venta,id_empleado,estado_pago);
CREATE INDEX ix_venta_cliente ON Venta(id_cliente);
CREATE TABLE Carga_diaria (
    id_carga NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado NUMBER NOT NULL REFERENCES Empleado(id_empleado),
    fecha DATE DEFAULT TRUNC(SYSDATE) NOT NULL CHECK (fecha = TRUNC(fecha)),
    id_producto NUMBER NOT NULL REFERENCES Productos(id_producto),
    cantidad_cargada NUMBER NOT NULL CHECK (cantidad_cargada >= 0 AND cantidad_cargada = TRUNC(cantidad_cargada)),
    CONSTRAINT uq_carga_dia UNIQUE(id_empleado,fecha,id_producto)
);
CREATE TABLE Cierre_caja (
    id_cierre NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado NUMBER NOT NULL REFERENCES Empleado(id_empleado),
    fecha DATE DEFAULT TRUNC(SYSDATE) NOT NULL CHECK (fecha = TRUNC(fecha)),
    total_esperado NUMBER(12,2) NOT NULL CHECK (total_esperado >= 0),
    monto_entregado NUMBER(12,2) NOT NULL CHECK (monto_entregado >= 0),
    diferencia NUMBER(12,2) NOT NULL,
    observacion VARCHAR2(500),
    esperado_efectivo NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (esperado_efectivo >= 0),
    esperado_transferencia NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (esperado_transferencia >= 0),
    entregado_efectivo NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (entregado_efectivo >= 0),
    entregado_transferencia NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (entregado_transferencia >= 0),
    CONSTRAINT uq_cierre_dia UNIQUE(id_empleado,fecha),
    CONSTRAINT ck_cierre_diferencia CHECK (diferencia = monto_entregado-total_esperado),
    CONSTRAINT ck_cierre_metodos CHECK (
        total_esperado = esperado_efectivo + esperado_transferencia
        AND monto_entregado = entregado_efectivo + entregado_transferencia)
);
CREATE TABLE Cierre_stock (
    id_cierre NUMBER NOT NULL REFERENCES Cierre_caja(id_cierre),
    id_producto NUMBER NOT NULL REFERENCES Productos(id_producto),
    cargado NUMBER NOT NULL CHECK (cargado >= 0 AND cargado = TRUNC(cargado)),
    vendido NUMBER NOT NULL CHECK (vendido >= 0 AND vendido = TRUNC(vendido)),
    devuelto NUMBER NOT NULL CHECK (devuelto >= 0 AND devuelto = TRUNC(devuelto)),
    diferencia NUMBER NOT NULL,
    PRIMARY KEY(id_cierre,id_producto),
    CONSTRAINT ck_cierre_stock CHECK (diferencia = vendido+devuelto-cargado)
);
-- Soporte durable para reintentos Oracle -> Mongo en la futura API.
CREATE TABLE Pendiente_Mongo (
    id_evento NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_venta NUMBER REFERENCES Venta(id_venta),
    tipo VARCHAR2(40) NOT NULL,
    payload CLOB NOT NULL CHECK (payload IS JSON),
    estado VARCHAR2(10) DEFAULT 'PENDIENTE' NOT NULL CHECK (estado IN ('PENDIENTE','PROCESADO')),
    intentos NUMBER DEFAULT 0 NOT NULL CHECK (intentos >= 0),
    ultimo_error VARCHAR2(500),
    creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
